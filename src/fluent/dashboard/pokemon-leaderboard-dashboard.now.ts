// the same way OOB dashboards like CMDB's "Configuration Item by
// Manufacturer" widget are: a Vertical bar macroponent whose
// componentProps bind straight to a table (x_2270446_pokenow_battle_log),
// grouped and counted - no Performance Analytics indicator needed. See the
// Service Portal leaderboard widget (sp-widget/pokemon-leaderboard) for the
// equivalent portal-page version; this is the same data, grouped live from
// the same battle_log table.
//
// Three tabs (by Pokemon / by Type / by Generation) instead of one tab with
// a live group-by dropdown: componentProps.additionalGroupByConfig renders
// a "Group by" selector, but it turned out to be a no-op for table-sourced
// widgets (only re-renders the picker, never re-queries) - confirmed by
// watching network traffic, since Fluent's docs don't cover this property
// and no working example existed on this instance either. Separate tabs
// reuse the one groupBy mechanism already proven to work.
//
// primary_type and generation are snapshotted onto battle_log at write
// time (see updatePokemonRecord in pokemon-battle.server.js) rather than
// dot-walked from the pokemon reference at query time, for the same
// reason - dot-walked groupByField was never confirmed to actually work,
// so every tab here groups off a field that lives directly on the
// dataSource table.
//
// Fluent files are a restricted declarative DSL (statically parsed, not
// executed), so each widget's componentProps is a fully literal object -
// no helper functions, string concatenation, or ternaries allowed.
